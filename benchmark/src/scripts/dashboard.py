def parse_arguments() -> argparse.Namespace:
    """Parse command-line arguments for the dashboard.

    Returns:
        Parsed arguments containing directory, x_axis, and y_axis selections
    """
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "-d",
        "--directory",
        type=str,
        help="Directory of artifacts.",
        default=None,
        required=False,
    )
    parser.add_argument(
        "-x",
        "--x_axis",
        type=str,
        help="Dictionary key for x axis.",
        default="faithfulness",
        required=False,
    )
    parser.add_argument(
        "-y",
        "--y_axis",
        type=str,
        help="Dictionary key for y axis.",
        default="interest",
        required=False,
    )
    return parser.parse_args()


