def load_all_data(dir_list: list[str]) -> DataFrame:
    """Load benchmark data into a single DataFrame when the directory list is updated.

    Parameters:
    dir_list : list of str
            The list of directory paths generated by the benchmark process.

    Returns:
        DataFrame with all the concatenated QA.json file data.
    """
    mainDF = DataFrame()
    for directory_path in dir_list:
        dirDF = load_a_dataframe(directory_path)
        mainDF = pandas.concat([mainDF, dirDF])
    return mainDF


def load_a_dataframe(directory_path: str) -> DataFrame:
    """
    Loads a single set of QA data from a directory into a DataFrame.

    Parameters:
    directory_path : str
            A directory path generated by the benchmark process,
            it will contain a set of folders each containing:
                DataPoint.json
                QA.json
                Spec.lean [may not be present of failed sample]

    Returns:
        DataFrame with all the QA.json file data, along with additional
        columns for the source (directory_path), faithfulness vs interest count,
        and a default column of 1's (Hack!).
    """
    # Read the contents of the QA files
    data: list[dict] = []
    for dir in os.listdir(directory_path):
        path = Path(directory_path) / dir / "QA.json"
        if os.path.exists(path):
            with open(path, "r") as file:
                qa_data = json.load(file)

                # Backwards compatibility: handle old field names
                if (
                    "faithfulness" in qa_data
                    and "faithfulness_subjective" not in qa_data
                ):
                    qa_data["faithfulness_subjective"] = qa_data["faithfulness"]
                if "interest" in qa_data and "interest_subjective" not in qa_data:
                    qa_data["interest_subjective"] = qa_data["interest"]

                # Flatten structural_faithfulness for easier plotting
                if (
                    "structural_faithfulness" in qa_data
                    and qa_data["structural_faithfulness"]
                ):
                    sf = qa_data["structural_faithfulness"]
                    qa_data["structural_param_coverage"] = sf.get(
                        "parameter_coverage", 0
                    )
                    qa_data["structural_type_correspondence"] = sf.get(
                        "type_correspondence", 0
                    )
                    qa_data["structural_strategy_coverage"] = sf.get(
                        "strategy_coverage", 0
                    )
                    qa_data["structural_assertion_coverage"] = sf.get(
                        "assertion_coverage", 0
                    )
                    qa_data["structural_dependency_coverage"] = sf.get(
                        "dependency_coverage", 0
                    )
                    qa_data["structural_overall"] = sf.get("overall", 0)

                data.append(qa_data)
    dataframe = DataFrame(data)
    # count points at each (faithfulness, interest) and add as new row
    f_i_row_counts: list[int] = []
    default_row_counts: list[int] = []
    source_names: list[str] = []
    for _, row in dataframe.iterrows():
        f_i_count_val: int = 0
        # Use subjective metrics for counting (backward compatible)
        if (
            "faithfulness_subjective" in dataframe.columns
            and "interest_subjective" in dataframe.columns
        ):
            if (
                dataframe.isin(
                    [row["faithfulness_subjective"], row["interest_subjective"]]
                )
                .any()
                .any()
            ):
                filt_x_df = dataframe[
                    dataframe["faithfulness_subjective"]
                    == row["faithfulness_subjective"]
                ]
                filt_xy_df = filt_x_df[
                    filt_x_df["interest_subjective"] == row["interest_subjective"]
                ]
                f_i_count_val = len(filt_xy_df)
        f_i_row_counts.append(f_i_count_val)
        default_row_counts.append(1)
        source_names.append(directory_path[-19:])
    dataframe["faithfulness_subjective vs interest_subjective"] = f_i_row_counts
    dataframe["default"] = default_row_counts
    dataframe["source"] = source_names
    return dataframe


def plot_dataframe(
    dataframe: DataFrame, args: argparse.Namespace
) -> panel.Column | panel.pane.Markdown:
    """
    Updates the plot when the DataFrame changes.

    Parameters:
    dataframe : DataFrame
            A dataframe filled with data to display.
    args: argparse.Namespace
            The default values passed via the command line.

    Returns:
        If directories have been selected, a Column displaying plot,
        otherwise a Pane displaying a message to select the directories.
    """
    if dataframe.empty or len(dataframe.columns) < 2:
        return panel.pane.Markdown("Point to an artifact directory to see the plot.")

    metric_list = dataframe.columns  # could fileter this if desired...

    # Map old arg names to new column names for backward compatibility
    x_axis_mapped = args.x_axis
    if args.x_axis == "faithfulness" and "faithfulness_subjective" in dataframe.columns:
        x_axis_mapped = "faithfulness_subjective"
    elif args.x_axis == "interest" and "interest_subjective" in dataframe.columns:
        x_axis_mapped = "interest_subjective"

    y_axis_mapped = args.y_axis
    if args.y_axis == "faithfulness" and "faithfulness_subjective" in dataframe.columns:
        y_axis_mapped = "faithfulness_subjective"
    elif args.y_axis == "interest" and "interest_subjective" in dataframe.columns:
        y_axis_mapped = "interest_subjective"

    x_axis_default = "default"
    if x_axis_mapped in dataframe.columns:
        x_axis_default = x_axis_mapped
    y_axis_default = "default"
    if y_axis_mapped in dataframe.columns:
        y_axis_default = y_axis_mapped

    # Make interactive parts
    x_axis_options = list(metric_list)
    y_axis_options = list(metric_list)
    size_options = list(metric_list)
    color_options = list(metric_list)
    x_axis_selector = panel.widgets.Select(
        name="Select X-Axis",
        options=x_axis_options,
        value=x_axis_default,
        visible=True,
        width=200,
    )
    y_axis_selector = panel.widgets.Select(
        name="Select Y-Axis",
        options=y_axis_options,
        value=y_axis_default,
        visible=True,
        width=200,
    )
    size_selector = panel.widgets.Select(
        name="Select Size Weight",
        options=size_options,
        value="default",
        visible=True,
        width=200,
    )
    color_selector = panel.widgets.Select(
        name="Select Color",
        options=color_options,
        value="default",
        visible=True,
        width=200,
    )

    # tooltip with just list of ids & names
    hover = HoverTool(
        tooltips=[("Sample", "@sample_id @sample_name")],
    )
    # main plot
    plot = dataframe.hvplot.scatter(
        # title=file_selector.value,
        x=x_axis_selector,
        y=y_axis_selector,
        c=color_selector,
        size=size_selector,
        scale=5,  # multiply point size by this
        alpha=0.7,
        hover_cols=["sample_name", "sample_id"],
        tools=[hover],
        responsive=True,
    )
    return panel.Column(
        panel.Row(x_axis_selector, y_axis_selector, color_selector, size_selector),
        plot,
        sizing_mode="stretch_both",
        name="Plot",
    )


def get_indicators(dir_list: list[str], styles) -> panel.FlexBox:
    """
    This is the top info section with the main indicators.
    It is refreshed when the direcory list changes.

    Parameters:
    dir_list : list of str
            The list of directory paths generated by the benchmark process.
    styles
            The default styles being used for this display.

    Returns:
        Two boxes, with counts of Datapoint.jsons and Spec.leans.
    """
    num_data_points: int = 0
    num_dirs_w_code: int = 0
    for directory_path in dir_list:
        for dir in os.listdir(directory_path):
            path = Path(directory_path) / dir / "Datapoint.json"
            if os.path.exists(path):
                num_data_points += 1
            path = Path(directory_path) / dir / "Spec.lean"
            if os.path.exists(path):
                num_dirs_w_code += 1

    return panel.FlexBox(
        panel.indicators.Number(
            value=num_data_points,
            name="Number DataPoints",
            format="{value:,.0f}",
            styles=styles,
        ),
        panel.indicators.Number(
            value=num_dirs_w_code,
            name="Number Successes",
            format="{value:,.0f}",
            styles=styles,
        ),
    )


def get_table(dataframe: DataFrame) -> panel.widgets.Tabulator | panel.pane.Markdown:
    """
    Updates the table when the DataFrame changes.

    Parameters:
    dataframe : DataFrame
            A dataframe filled with data to display.

    Returns:
        If directories have been selected, a Tabulator displaying table,
        otherwise a Pane displaying a message to select the directories.
    """
    if dataframe.empty or len(dataframe.columns) < 2:
        return panel.pane.Markdown("Point to an artifact directory to see the table.")
    return panel.widgets.Tabulator(dataframe, sizing_mode="stretch_both", name="Table")


def dashboard():
    """Main entry point for the dashboard display.

    Examples:
        panel serve dashboard.py
          or
        panel serve dashboard.py --args -d "../benchmark/artifacts/2025-10-01T13-26-28" -x "interest" -y "faithfulness"
    """
    ACCENT = "blue"
    styles = {
        "box-shadow": "rgba(50, 50, 93, 0.25) 0px 6px 12px -2px, rgba(0, 0, 0, 0.3) 0px 3px 7px -3px",
        "border-radius": "4px",
        "padding": "10px",
    }

    args = parse_arguments()

    if args.directory is not None:
        file_selector = panel.widgets.FileSelector(
            directory="../benchmark/artifacts/",
            name="Select Directory",
            value=[args.directory],
        )
    else:
        file_selector = panel.widgets.FileSelector(
            directory="../benchmark/artifacts/", name="Select Directory"
        )

    dataframe = panel.bind(load_all_data, file_selector)
    indicators = panel.bind(get_indicators, file_selector, styles)
    plot = panel.bind(plot_dataframe, dataframe, args)
    table = panel.bind(get_table, dataframe)

    file_col = panel.Column(
        file_selector,
        sizing_mode="stretch_both",
        name="Source",
    )
    plot_col = panel.Column(plot, sizing_mode="stretch_both", name="Plot")
    table_col = panel.Column(table, sizing_mode="stretch_both", name="Table")

    tabs = panel.Tabs(
        file_col,
        plot_col,
        table_col,
        styles=styles,
        sizing_mode="stretch_width",
        height=600,
        margin=10,
    )

    return panel.template.FastListTemplate(
        title="FVSpec Dashboard",
        # sidebar=[],
        sidebar_width=60,
        main=[panel.Column(indicators, tabs, sizing_mode="stretch_both")],
        main_layout=None,
        accent=ACCENT,
    )


dashboard().servable()
