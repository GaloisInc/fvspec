"""Generate LSpec test suites from extracted test cases.

DEPRECATED: This module is no longer used in the pipeline. Unit tests are now
generated by the LLM-based units agent (formalize.units.agent).

Kept for reference but not actively maintained.
"""

from generate.scaffold.formalize.units.v0.models import TestCase, TestSuite


def generate_lean_test(test: TestCase) -> str:
    """Generate a single LSpec test line.

    Args:
        test: The test case to generate

    Returns:
        A single line of LSpec test code (without newline)

    Example:
        >>> test = TestCase(
        ...     func_name="double",
        ...     inputs=["[1, 2, 3]"],
        ...     expected_output="[2, 4, 6]",
        ...     test_name="double basic"
        ... )
        >>> generate_lean_test(test)
        'test "double basic" (double [1, 2, 3] = [2, 4, 6])'
    """
    inputs_str = " ".join(test.inputs)
    return f'test "{test.test_name}" ({test.func_name} {inputs_str} = {test.expected_output})'


def generate_float_eval(test: TestCase) -> str:
    """Generate a float test with #eval and expected value comment.

    Args:
        test: The float test case to generate

    Returns:
        Multi-line string with comment and #eval

    Example:
        >>> test = TestCase(
        ...     func_name="sqrt",
        ...     inputs=["2.0"],
        ...     expected_output="1.41421356",
        ...     is_float=True,
        ...     test_name="sqrt of 2"
        ... )
        >>> print(generate_float_eval(test))
        -- Expected: ~1.41421356 (rtol=1e-05, atol=1e-08)
        #eval sqrt 2.0
    """
    inputs_str = " ".join(test.inputs)
    return f"-- Expected: ~{test.expected_output} (rtol={test.rtol}, atol={test.atol})\n#eval {test.func_name} {inputs_str}"


def generate_test_suite(suite: TestSuite) -> str:
    """Generate complete LSpec test suite code.

    Args:
        suite: The test suite containing exact and float tests

    Returns:
        Complete Lean code with imports, test definitions, and #lspec command

    Example:
        >>> suite = TestSuite(
        ...     exact_tests=[
        ...         TestCase(func_name="f", inputs=["1"], expected_output="2", test_name="test1"),
        ...         TestCase(func_name="f", inputs=["2"], expected_output="4", test_name="test2"),
        ...     ],
        ...     float_tests=[],
        ...     extraction_stats={"method": "ast", "count": 2}
        ... )
        >>> print(generate_test_suite(suite))
        import LSpec
        <BLANKLINE>
        def tests : TestSeq :=
          test "test1" (f 1 = 2) $
          test "test2" (f 2 = 4)
        <BLANKLINE>
        #lspec tests
    """
    lines: list[str] = []

    # Always import LSpec if we have any tests
    if suite.exact_tests or suite.float_tests:
        lines.append("import LSpec")
        lines.append("")

    # Generate exact tests with LSpec
    if suite.exact_tests:
        lines.append("def tests : TestSeq :=")
        for i, test in enumerate(suite.exact_tests):
            test_line = generate_lean_test(test)
            # Add $ separator for all but the last test
            if i < len(suite.exact_tests) - 1:
                test_line += " $"
            lines.append(f"  {test_line}")
        lines.append("")
        lines.append("#lspec tests")

    # Generate float tests with #eval
    if suite.float_tests:
        if suite.exact_tests:
            lines.append("")
        lines.append("-- Float tests (external validation)")
        for test in suite.float_tests:
            lines.append(generate_float_eval(test))

    return "\n".join(lines)
