"""Merge multiple Lean modules into a single coherent file.

This module handles the intelligent merging of Lean code blocks generated by
different impl agents, ensuring:
- Deduplicated imports at the top
- Single namespace block
- No redefinitions
- Clean structure
"""

import re

from pydantic import BaseModel

# Regex pattern for matching Lean definition keywords and capturing the identifier name
_LEAN_DEF_PATTERN = r"^\s*(structure|def|theorem|lemma|axiom|opaque|inductive|class|instance|abbrev)\s+(\w+)"
# Pattern for matching definition keywords without capturing the name
_LEAN_DEF_KEYWORD_PATTERN = (
    r"^\s*(structure|def|theorem|lemma|axiom|opaque|inductive|class|instance|abbrev)\s+"
)


class LeanModule(BaseModel):
    """Parsed components of a Lean module."""

    imports: list[str]  # Import statements (e.g., "import Batteries")
    namespace_content: str  # Content inside namespace block
    namespace_name: str  # e.g., "Fvspec.Impl"
    preamble: str  # Comments/docs before imports


def parse_lean_module(code: str) -> LeanModule:
    """Parse Lean code into structured components.

    Args:
        code: Lean source code (may contain imports, namespace, etc.)

    Returns:
        Parsed module with separated imports and namespace content

    Examples:
        >>> code = '''import Batteries
        ... namespace Fvspec.Impl
        ... def foo := 1
        ... end Fvspec.Impl'''
        >>> module = parse_lean_module(code)
        >>> module.imports
        ['import Batteries']
        >>> 'def foo := 1' in module.namespace_content
        True
    """
    imports: list[str] = []
    preamble_lines: list[str] = []
    namespace_name = "Fvspec.Impl"  # Default
    namespace_content = ""

    lines = code.split("\n")
    i = 0

    # Phase 1: Collect preamble (comments before imports)
    while i < len(lines):
        line = lines[i].strip()
        if line.startswith("--") or not line:
            preamble_lines.append(lines[i])
            i += 1
        elif line.startswith("import "):
            break
        else:
            break

    # Phase 2: Collect imports
    while i < len(lines):
        line = lines[i].strip()
        if line.startswith("import "):
            imports.append(line)
            i += 1
        elif not line or line.startswith("--"):
            # Skip blank lines and comments between imports
            i += 1
        else:
            break

    # Phase 3: Find namespace declaration
    namespace_start = -1
    namespace_end = -1

    for j in range(i, len(lines)):
        line = lines[j].strip()
        if match := re.match(r"namespace\s+([\w.]+)", line):
            namespace_name = match.group(1)
            namespace_start = j
            break

    if namespace_start >= 0:
        # Find matching end
        for j in range(namespace_start + 1, len(lines)):
            line = lines[j].strip()
            if line.startswith(f"end {namespace_name}") or line == "end":
                namespace_end = j
                break

        if namespace_end > namespace_start:
            # Extract content between namespace and end
            content_lines = lines[namespace_start + 1 : namespace_end]
            namespace_content = "\n".join(content_lines)
        else:
            # No matching end found - take rest of file
            content_lines = lines[namespace_start + 1 :]
            namespace_content = "\n".join(content_lines)
    else:
        # No namespace found - treat remaining as content
        remaining_lines = lines[i:]
        namespace_content = "\n".join(remaining_lines)

    preamble = "\n".join(preamble_lines).strip()

    return LeanModule(
        imports=imports,
        namespace_content=namespace_content.strip(),
        namespace_name=namespace_name,
        preamble=preamble,
    )


def merge_lean_modules(
    modules: list[LeanModule], namespace: str = "Fvspec.Impl"
) -> str:
    """Merge multiple parsed Lean modules into single coherent file.

    Args:
        modules: List of parsed Lean modules
        namespace: Target namespace name (default: Fvspec.Impl)

    Returns:
        Merged Lean source code with:
        - Deduplicated imports at top
        - Single namespace block
        - All content inside namespace

    Examples:
        >>> m1 = LeanModule(['import Batteries'], 'def foo := 1', 'Fvspec.Impl', '')
        >>> m2 = LeanModule(['import Batteries'], 'def bar := 2', 'Fvspec.Impl', '')
        >>> merged = merge_lean_modules([m1, m2])
        >>> merged.count('import Batteries')
        1
        >>> merged.count('namespace Fvspec.Impl')
        1
    """
    if not modules:
        # Return empty namespace
        return f"namespace {namespace}\n\nend {namespace}\n"

    # Deduplicate imports (preserve order)
    seen_imports = set()
    unique_imports = []
    for module in modules:
        for imp in module.imports:
            if imp not in seen_imports:
                seen_imports.add(imp)
                unique_imports.append(imp)

    # Collect namespace content with deduplication of definitions
    # Track definition names to prevent duplicates (structures, defs, theorems, etc.)
    seen_definitions = set()
    content_blocks = []

    for module in modules:
        if not module.namespace_content.strip():
            continue

        # Extract definition names from this module's content
        content = module.namespace_content.strip()
        lines = content.split("\n")

        # Build filtered content by checking each definition
        filtered_lines = []
        skip_until_next_def = False
        in_docstring = False
        pending_docstring_lines = []

        for line in lines:
            # Track docstrings (Lean uses /-- ... -/ for doc comments)
            stripped = line.strip()
            if stripped.startswith("/--") and not in_docstring:
                # Start of docstring
                pending_docstring_lines = [line]
                if "-/" not in stripped:
                    # Multi-line docstring starting
                    in_docstring = True
                continue
            elif in_docstring:
                # Inside multi-line docstring
                pending_docstring_lines.append(line)
                if "-/" in stripped:
                    # End of multi-line docstring
                    in_docstring = False
                continue

            # Check if this line starts a definition
            # Match: structure/def/theorem/lemma/axiom/opaque/inductive/class/instance/abbrev
            def_match = re.match(_LEAN_DEF_PATTERN, line)

            if def_match:
                def_name = def_match.group(2)
                if def_name in seen_definitions:
                    # Skip this definition (already exists)
                    # Also discard its docstring
                    pending_docstring_lines = []
                    skip_until_next_def = True
                    continue
                else:
                    # Track this definition and include it
                    seen_definitions.add(def_name)
                    skip_until_next_def = False
                    # Add any pending docstring before the definition
                    filtered_lines.extend(pending_docstring_lines)
                    pending_docstring_lines = []
                    filtered_lines.append(line)
            else:
                # Not a definition start
                # Check if this line starts a NEW definition (to stop skipping)
                if skip_until_next_def:
                    # Check if this is another top-level definition
                    next_def = re.match(_LEAN_DEF_KEYWORD_PATTERN, line)
                    if next_def:
                        # New definition found, re-evaluate it
                        def_match = re.match(_LEAN_DEF_PATTERN, line)
                        if def_match:
                            def_name = def_match.group(2)
                            if def_name not in seen_definitions:
                                seen_definitions.add(def_name)
                                skip_until_next_def = False
                                # Add pending docstring if any
                                filtered_lines.extend(pending_docstring_lines)
                                pending_docstring_lines = []
                                filtered_lines.append(line)
                            else:
                                # Still a duplicate, keep skipping and discard docstring
                                pending_docstring_lines = []
                    # Otherwise keep skipping
                else:
                    # Not skipping, include the line
                    # But if there's a pending docstring without a definition, add it
                    if pending_docstring_lines:
                        filtered_lines.extend(pending_docstring_lines)
                        pending_docstring_lines = []
                    filtered_lines.append(line)

        # Add filtered content if non-empty
        filtered_content = "\n".join(filtered_lines).strip()
        if filtered_content:
            content_blocks.append(filtered_content)

    # Build merged file
    parts = []

    # Imports section
    if unique_imports:
        parts.append("\n".join(unique_imports))
        parts.append("")  # Blank line after imports

    # Namespace section
    parts.append(f"namespace {namespace}")
    parts.append("")  # Blank line after namespace declaration

    # Content
    if content_blocks:
        parts.append("\n\n".join(content_blocks))

    parts.append("")  # Blank line before end
    parts.append(f"end {namespace}")

    return "\n".join(parts)


def merge_lean_code_strings(
    code_blocks: list[str], namespace: str = "Fvspec.Impl"
) -> str:
    r"""Convenience function to merge Lean code strings directly.

    Args:
        code_blocks: List of Lean source code strings
        namespace: Target namespace name

    Returns:
        Merged Lean source code

    Examples:
        >>> code1 = "import Batteries\nnamespace Fvspec.Impl\ndef foo := 1\nend Fvspec.Impl"
        >>> code2 = "import Batteries\nnamespace Fvspec.Impl\ndef bar := 2\nend Fvspec.Impl"
        >>> merged = merge_lean_code_strings([code1, code2])
        >>> 'def foo := 1' in merged and 'def bar := 2' in merged
        True
        >>> merged.count('import Batteries')
        1
    """
    modules = [parse_lean_module(code) for code in code_blocks if code.strip()]
    return merge_lean_modules(modules, namespace)


def append_to_lean_file(existing_code: str, new_code: str) -> str:
    r"""Append new Lean code to existing module, maintaining clean structure.

    This is the primary API for orchestration - call this instead of string
    concatenation to maintain proper Lean module structure.

    Args:
        existing_code: Current content of Impl.lean (may be empty)
        new_code: New code to add (e.g., from dependency impl)

    Returns:
        Merged code with proper structure

    Examples:
        >>> existing = "import Batteries\nnamespace Fvspec.Impl\ndef foo := 1\nend Fvspec.Impl"
        >>> new = "import Batteries\nnamespace Fvspec.Impl\ndef bar := 2\nend Fvspec.Impl"
        >>> result = append_to_lean_file(existing, new)
        >>> 'def foo := 1' in result and 'def bar := 2' in result
        True
        >>> result.count('namespace Fvspec.Impl')
        1
    """
    if not existing_code.strip():
        # First module - just return it
        return new_code

    if not new_code.strip():
        # Nothing to add
        return existing_code

    # Merge both
    return merge_lean_code_strings([existing_code, new_code])
